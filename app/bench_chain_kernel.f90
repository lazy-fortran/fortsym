program bench_chain_kernel
    ! Operation counts of two chain-rule-heavy kernels, generated by direct
    ! symbolic differentiation of the expanded expressions and by derivative
    ! propagation through named intermediates (fortsym_chain). Counts are taken
    ! over the hash-consed DAG of all outputs, which is the work after global
    ! CSE. They compare generated variants and do not replace timings.
    !
    ! hessian: value, gradient and Hessian in (r, theta, phi, p) of v, H and p_theta of
    !   v = (p - A/c)/h, H = v**2/2 + mu*B + Phi, p_theta = g*v + T/c,
    !   with A, h, B, Phi, g, T opaque functions of (r, theta, phi).
    ! rates: guiding-centre rates of Boozer fields, B(r, theta, phi) and
    !   profiles of r, with v/B = (p - a/c)/b_phi as the intermediate.
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, func, operator(+), operator(-), &
        operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_chain, only: chain_t, fold_numbers
    use fortsym_kernel, only: count_operations, operation_count_t
    implicit none

    write (*, '(a)') 'kernel,variant,additions,multiplications,divisions,powers,flops'
    call hessian()
    call rates()

contains

    subroutine hessian()
        type(arena_t), target :: arena
        type(chain_t) :: c
        type(expr_t) :: x(4), fields(6), mu, ro0, v, chained(3), direct(3)
        type(expr_t), allocatable :: chain_roots(:), direct_roots(:)
        integer :: i, j, m
        character(3), parameter :: names(6) = ['A  ', 'h  ', 'B  ', 'Phi', 'g  ', 'T  ']

        call arena%init()
        x = [sym(arena, 'r'), sym(arena, 'theta'), sym(arena, 'phi'), sym(arena, 'p')]
        do i = 1, 6
            fields(i) = func(trim(names(i)), x(1:3))
        end do
        mu = sym(arena, 'mu')
        ro0 = sym(arena, 'c')
        call c%init(x)
        v = c%let('v', (x(4) - fields(1)/ro0)/fields(2))
        chained = [v, v**2/2 + mu*fields(3) + fields(4), fields(5)*v + fields(6)/ro0]
        direct(1) = (x(4) - fields(1)/ro0)/fields(2)
        direct(2) = direct(1)**2/2 + mu*fields(3) + fields(4)
        direct(3) = fields(5)*direct(1) + fields(6)/ro0
        allocate (chain_roots(0), direct_roots(0))
        do m = 1, 3
            chain_roots = [chain_roots, chained(m)]
            direct_roots = [direct_roots, direct(m)]
            do i = 1, 4
                chain_roots = [chain_roots, c%d(chained(m), i)]
                direct_roots = [direct_roots, diff(direct(m), x(i))]
                do j = i, 4
                    chain_roots = [chain_roots, c%d(c%d(chained(m), i), j)]
                    direct_roots = [direct_roots, diff(diff(direct(m), x(i)), x(j))]
                end do
            end do
        end do
        call report('hessian', 'direct', direct_roots)
        call report('hessian', 'chain', [c%defs(c%needed(chain_roots)), chain_roots])
    end subroutine hessian

    subroutine rates()
        type(arena_t), target :: arena
        type(chain_t) :: c, unused
        type(expr_t) :: x(4), fields(6), chain_rates(4), direct_rates(4)

        call arena%init()
        x = [sym(arena, 'r'), sym(arena, 'theta'), sym(arena, 'phi'), sym(arena, 'p')]
        ! mu, c, a_phi, B_theta, B_phi, A_theta(r) and B(r, theta, phi).
        fields = [sym(arena, 'mu'), sym(arena, 'c'), func('aphi', x(1:1)), &
            func('btheta', x(1:1)), func('bphi', x(1:1)), func('ath', x(1:1))]
        call c%init(x)
        chain_rates = gc_rates(c, .true., x, fields, func('bmod', x(1:3)))
        call unused%init(x)
        direct_rates = gc_rates(unused, .false., x, fields, func('bmod', x(1:3)))
        call report('rates', 'direct', direct_rates)
        call report('rates', 'chain', [c%defs(c%needed(chain_rates)), chain_rates])
    end subroutine rates

    function gc_rates(c, use_chain, x, fields, bmod) result(out)
        type(chain_t), intent(inout) :: c
        logical, intent(in) :: use_chain
        type(expr_t), intent(in) :: x(4), fields(6), bmod
        type(expr_t) :: out(4), vpar, hth, hph, h, pth, dh(3), dpth(3), hp
        type(expr_t) :: mu, ro0, aphi, btheta, bphi, ath
        integer :: k

        mu = fields(1)
        ro0 = fields(2)
        aphi = fields(3)
        btheta = fields(4)
        bphi = fields(5)
        ath = fields(6)
        hth = btheta/bmod
        hph = bphi/bmod
        if (use_chain) then
            vpar = bmod*c%let('pob', c%let('q', x(4) - aphi/ro0)/bphi)
        else
            vpar = (x(4) - aphi/ro0)/hph
        end if
        h = vpar**2/2 + mu*bmod
        pth = hth*vpar + ath/ro0
        do k = 1, 3
            if (use_chain) then
                dh(k) = c%d(h, k)
                dpth(k) = c%d(pth, k)
            else
                dh(k) = diff(h, x(k))
                dpth(k) = diff(pth, x(k))
            end if
        end do
        hp = dh(1)/dpth(1)
        out(1) = -(dh(2) - hth/hph*dh(3))/dpth(1)
        out(2) = hp
        out(3) = (vpar - hp*hth)/hph
        out(4) = -(dh(3) - hp*dpth(3))
        if (use_chain) then
            do k = 1, 4
                out(k) = fold_numbers(out(k))
            end do
        end if
    end function gc_rates

    subroutine report(kernel, variant, roots)
        character(*), intent(in) :: kernel, variant
        type(expr_t), intent(in) :: roots(:)
        type(operation_count_t) :: n

        n = count_operations(roots)
        write (*, '(a,",",a,5(",",i0))') kernel, variant, n%additions, &
            n%multiplications, n%divisions, n%powers, n%flops
    end subroutine report

end program bench_chain_kernel
